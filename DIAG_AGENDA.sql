   y la funcion de disponibilidad:
     1) columnas/tipos de la agenda vieja (LK_AGENDA_EMPLEADO)
     2) mapeo empleado <-> consultor (VCT_CONSULTORES)
     3) columnas de las visitas nuevas (VCT_PROYECTOS_VISITAS*)
     4) columnas del calendario de feriados (dbo.Calendar)
     5) muestras de datos para ver como se guarda hoy
   No cambia NADA. Correr con Query > SQLCMD Mode (F5).
   ============================================================ */
