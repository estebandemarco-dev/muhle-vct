USE [MuhlePROD];
SET NOCOUNT ON;

PRINT '===== 0) EXISTENCIA DE OBJETOS =====';
SELECT N AS OBJETO,
       CASE WHEN OBJECT_ID(N) IS NULL THEN 'FALTA' ELSE 'ok' END AS ESTADO
FROM (VALUES
    ('dbo.LK_AGENDA_EMPLEADO'),
    ('dbo.LK_AGENDA'),
    ('dbo.LK_EMPLEADOS'),
    ('dbo.LK_EMPLEADOS_DIAS'),
    ('dbo.VCT_CONSULTORES'),
    ('dbo.VCT_PROYECTOS_VISITAS'),
    ('dbo.VCT_PROYECTOS_VISITAS_CONSULTORES'),
    ('dbo.VCT_PROYECTOS_VISITAS_REGISTRO'),
    ('dbo.Calendar'),
    ('dbo.VCT_PRM_AGENDA_CONSULTOR')
) T(N)
ORDER BY CASE WHEN OBJECT_ID(N) IS NULL THEN 0 ELSE 1 END, N;

PRINT '';
PRINT '===== 1) COLUMNAS: LK_AGENDA_EMPLEADO =====';
SELECT ORDINAL_POSITION AS POS, COLUMN_NAME, DATA_TYPE,
       CHARACTER_MAXIMUM_LENGTH AS LEN, NUMERIC_PRECISION AS PREC,
       NUMERIC_SCALE AS SCALE, IS_NULLABLE, COLUMN_DEFAULT
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'LK_AGENDA_EMPLEADO'
ORDER BY ORDINAL_POSITION;

PRINT '';
PRINT '===== 1b) COLUMNAS: LK_AGENDA (cabecera/asignacion vieja) =====';
SELECT ORDINAL_POSITION AS POS, COLUMN_NAME, DATA_TYPE,
       CHARACTER_MAXIMUM_LENGTH AS LEN, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'LK_AGENDA'
ORDER BY ORDINAL_POSITION;

PRINT '';
PRINT '===== 2) COLUMNAS: VCT_CONSULTORES (para mapear empleado<->consultor) =====';
SELECT ORDINAL_POSITION AS POS, COLUMN_NAME, DATA_TYPE,
       CHARACTER_MAXIMUM_LENGTH AS LEN, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'VCT_CONSULTORES'
ORDER BY ORDINAL_POSITION;

PRINT '';
PRINT '===== 3) COLUMNAS: VCT_PROYECTOS_VISITAS =====';
SELECT ORDINAL_POSITION AS POS, COLUMN_NAME, DATA_TYPE,
       CHARACTER_MAXIMUM_LENGTH AS LEN, NUMERIC_PRECISION AS PREC,
       NUMERIC_SCALE AS SCALE, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'VCT_PROYECTOS_VISITAS'
ORDER BY ORDINAL_POSITION;

PRINT '';
PRINT '===== 3b) COLUMNAS: VCT_PROYECTOS_VISITAS_CONSULTORES =====';
SELECT ORDINAL_POSITION AS POS, COLUMN_NAME, DATA_TYPE,
       CHARACTER_MAXIMUM_LENGTH AS LEN, NUMERIC_PRECISION AS PREC,
       NUMERIC_SCALE AS SCALE, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'VCT_PROYECTOS_VISITAS_CONSULTORES'
ORDER BY ORDINAL_POSITION;

PRINT '';
PRINT '===== 3c) COLUMNAS: VCT_PROYECTOS_VISITAS_REGISTRO =====';
SELECT ORDINAL_POSITION AS POS, COLUMN_NAME, DATA_TYPE,
       CHARACTER_MAXIMUM_LENGTH AS LEN, NUMERIC_PRECISION AS PREC,
       NUMERIC_SCALE AS SCALE, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'VCT_PROYECTOS_VISITAS_REGISTRO'
ORDER BY ORDINAL_POSITION;

PRINT '';
PRINT '===== 4) COLUMNAS: dbo.Calendar (feriados) =====';
SELECT ORDINAL_POSITION AS POS, COLUMN_NAME, DATA_TYPE,
       CHARACTER_MAXIMUM_LENGTH AS LEN, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_NAME = 'Calendar'
ORDER BY ORDINAL_POSITION;

PRINT '';
PRINT '===== 5) VOLUMENES =====';
SELECT 'LK_AGENDA_EMPLEADO' AS TABLA, COUNT(*) AS FILAS FROM dbo.LK_AGENDA_EMPLEADO
UNION ALL SELECT 'VCT_CONSULTORES', COUNT(*) FROM dbo.VCT_CONSULTORES
UNION ALL SELECT 'VCT_PROYECTOS_VISITAS', COUNT(*) FROM dbo.VCT_PROYECTOS_VISITAS
UNION ALL SELECT 'VCT_PROYECTOS_VISITAS_CONSULTORES', COUNT(*) FROM dbo.VCT_PROYECTOS_VISITAS_CONSULTORES;

PRINT '';
PRINT '===== 6) MUESTRA LK_AGENDA_EMPLEADO (20 filas con mas horas) =====';
SELECT TOP 20 *
FROM dbo.LK_AGENDA_EMPLEADO
ORDER BY ISNULL(HORAS,0) DESC, FECHA DESC;

PRINT '';
PRINT '===== 6b) LK_AGENDA_EMPLEADO: cuantas filas tienen HOLIDAYTEXT (= asignado) =====';
SELECT CASE WHEN ISNULL(CONVERT(VARCHAR(50),HOLIDAYTEXT),'') = '' THEN 'sin holidaytext'
            ELSE 'con holidaytext (asignado)' END AS TIPO,
       COUNT(*) AS FILAS
FROM dbo.LK_AGENDA_EMPLEADO
GROUP BY CASE WHEN ISNULL(CONVERT(VARCHAR(50),HOLIDAYTEXT),'') = '' THEN 'sin holidaytext'
              ELSE 'con holidaytext (asignado)' END;

PRINT '';
PRINT '===== 7) MUESTRA VCT_CONSULTORES (5 filas, para ver ID_EMPLEADO / ID_USUARIO) =====';
SELECT TOP 5 * FROM dbo.VCT_CONSULTORES ORDER BY 1;

PRINT '';
PRINT '===== 8) MUESTRA VCT_PROYECTOS_VISITAS (5) + _CONSULTORES (5) =====';
SELECT TOP 5 * FROM dbo.VCT_PROYECTOS_VISITAS ORDER BY 1 DESC;
SELECT TOP 5 * FROM dbo.VCT_PROYECTOS_VISITAS_CONSULTORES ORDER BY 1 DESC;

PRINT '';
PRINT '===== FIN DIAG_AGENDA =====';
GO
